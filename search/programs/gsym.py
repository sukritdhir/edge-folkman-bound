"""Generic symmetric problem data for the interior-point solver exp/ipm_g.py.

Input: a graph (boolean adjacency matrix A), an automorphism `perm` (array, v -> perm[v]) and a set `removed` of
vertices that perm maps to itself.  The base graph is G' = G - removed.  The cyclic group generated by perm must act
freely on the edges of G' that lie in triangles and on the triangles of G' (all orbits of full length q; checked).
Vertices may be fixed.  Edges of G' that lie in no triangle are ignored.

make(A, perm, removed) returns (G_, Sx) with the attributes that the solver uses (the same names as in symsub.SymSub):
  G_.n, G_.ends (edge id -> its two ends)
  Sx.q, Sx.nrep (edge orbits), Sx.no (triangle orbits), Sx.oa, Sx.oi (no x 3: the edge of the representative triangle
  of orbit o is perm^oi (representative edge of orbit oa)), Sx.edge_rep, Sx.edge_off (edge id -> orbit, offset),
  Sx.tri_kept (triangle -> its 3 edge ids), Sx.tri_orbit, Sx.tri_verts (triangle -> its 3 vertices),
  Sx.rep_tri (orbit -> index of its representative triangle), Sx.rep_edge (orbit -> edge id of its representative),
  Sx.keep, Sx.nv, Sx.degrees(mu).
"""
import numpy as np
import gen


class _O:
    pass


def perm_order(perm):
    n = len(perm); x = perm.copy(); q = 1; idn = np.arange(n)
    while not (x == idn).all():
        x = perm[x]; q += 1
        assert q <= 10 ** 6
    return q


def make(A, perm, removed=(), drop_short=False):
    """drop_short: triangles whose orbit under perm is shorter than q are left out (they get no weight; their edges
    stay in the system as far as they lie in other triangles)."""
    n = len(A); perm = np.asarray(perm, dtype=np.int64)
    keep = np.ones(n, dtype=bool); keep[list(removed)] = False
    assert sorted(perm.tolist()) == list(range(n))
    assert (A[np.ix_(perm, perm)] == A).all(), "perm is not an automorphism"
    assert (keep[perm] == keep).all(), "the removed set is not invariant"
    q = perm_order(perm)
    Ab = A & keep[:, None] & keep[None, :]
    T = gen.triangles(Ab)
    if drop_short:
        tc = (T[:, 0] * n + T[:, 1]) * n + T[:, 2]
        od = np.argsort(tc); ts = tc[od]
        PT = np.sort(perm[T], axis=1); pc = (PT[:, 0] * n + PT[:, 1]) * n + PT[:, 2]
        nx = od[np.searchsorted(ts, pc)]
        cur = nx.copy(); short = np.zeros(len(T), dtype=bool)
        for k in range(1, q):
            short |= (cur == np.arange(len(T)))                            # pi^k T = T for some 0 < k < q
            cur = nx[cur]
        # triangles with an edge whose orbit is short (both ends have short vertex orbits; q is odd here)
        vlen = np.zeros(n, dtype=np.int64); x = perm.copy()
        for k in range(1, q + 1):
            vlen[(vlen == 0) & (x == np.arange(n))] = k
            x = perm[x]
        for (i, j) in ((0, 1), (0, 2), (1, 2)):
            short |= np.lcm(vlen[T[:, i]], vlen[T[:, j]]) < q
        if short.any(): T = T[~short]
    ends, tri, deg = gen.edge_system(Ab, T)
    m = len(ends); nt = len(T)
    # edge orbits
    code = ends[:, 0] * n + ends[:, 1]                                    # sorted (np.unique)
    u, v = perm[ends[:, 0]], perm[ends[:, 1]]
    nxt = np.searchsorted(code, np.minimum(u, v) * n + np.maximum(u, v))
    assert (code[nxt] == np.minimum(u, v) * n + np.maximum(u, v)).all()
    edge_rep = -np.ones(m, dtype=np.int64); edge_off = np.zeros(m, dtype=np.int64); rep_edge = []
    for i in range(m):
        if edge_rep[i] >= 0: continue
        j = i
        for k in range(q):
            assert edge_rep[j] < 0, "an edge orbit is shorter than q"
            edge_rep[j] = len(rep_edge); edge_off[j] = k; j = int(nxt[j])
        assert j == i
        rep_edge.append(i)
    nrep = len(rep_edge); assert nrep * q == m
    # triangle orbits
    tcode = (T[:, 0] * n + T[:, 1]) * n + T[:, 2]
    order = np.argsort(tcode); tsorted = tcode[order]
    PT = np.sort(perm[T], axis=1)
    pc = (PT[:, 0] * n + PT[:, 1]) * n + PT[:, 2]
    pos = np.searchsorted(tsorted, pc); assert (tsorted[pos] == pc).all()
    tnxt = order[pos]
    tri_orbit = -np.ones(nt, dtype=np.int64); rep_tri = []
    for i in range(nt):
        if tri_orbit[i] >= 0: continue
        j = i
        for k in range(q):
            assert tri_orbit[j] < 0, "a triangle orbit is shorter than q"
            tri_orbit[j] = len(rep_tri); j = int(tnxt[j])
        assert j == i
        rep_tri.append(i)
    no = len(rep_tri); assert no * q == nt
    rep_tri = np.array(rep_tri)
    G_ = _O(); G_.n = n; G_.ends = ends
    Sx = _O()
    Sx.q = q; Sx.nrep = nrep; Sx.no = no
    Sx.oa = edge_rep[tri[rep_tri]]; Sx.oi = edge_off[tri[rep_tri]]
    Sx.edge_rep = edge_rep; Sx.edge_off = edge_off; Sx.tri_kept = tri; Sx.tri_orbit = tri_orbit; Sx.tri_verts = T
    Sx.rep_tri = rep_tri; Sx.rep_edge = np.array(rep_edge)
    Sx.keep = keep; Sx.nv = int(keep.sum()); Sx.deg = deg
    Sx.degrees = lambda mu: np.bincount(Sx.oa.ravel(), weights=np.repeat(np.asarray(mu, float), 3), minlength=nrep)
    return G_, Sx


def survival(G, Sx, X):
    """n_a / q and m_o / q for the vertex set X: the fractions of the edges of orbit a / of the triangles of orbit o
    that avoid X."""
    bad = np.zeros(G.n, dtype=bool); bad[list(X)] = True
    eok = ~bad[G.ends[:, 0]] & ~bad[G.ends[:, 1]]
    na = np.bincount(Sx.edge_rep[eok], minlength=Sx.nrep).astype(float)
    tri = Sx.tri_kept
    tok = eok[tri[:, 0]] & eok[tri[:, 1]] & eok[tri[:, 2]]
    mo = np.bincount(Sx.tri_orbit[tok], minlength=Sx.no).astype(float)
    return na / Sx.q, mo / Sx.q


# ---------------------------------------------------------------------------------------------------------
#  problem specifications:  "Y:p:e0:c:J:step"  = Q(p, e0) restricted to the vertices i with (i mod c) in J,
#                                                 symmetry: the shift by e0*step
#                           "U:p:e0:pts"        = Q(p, e0) minus the fibres over the listed points (the first
#                                                 one is the fixed point of the unipotent symmetry of order p);
#                                                 only the first fibre may be removed for the symmetry to act
# ---------------------------------------------------------------------------------------------------------
def from_spec(spec):
    import qfam
    f = spec.split(":")
    if f[0] == "Y":
        p, e0, c = int(f[1]), int(f[2]), int(f[3]); J = [int(x) for x in f[4].split(",")]; step = int(f[5])
        Q = qfam.QGraph(p, e0); n = Q.n
        assert (e0 * step) % c == 0 and n % c == 0
        removed = [i for i in range(n) if (i % c) not in J]
        perm = (np.arange(n) + e0 * step) % n
        return Q.A, perm, removed, {"family": "Q", "p": p, "e0": e0, "theta": Q.theta, "step": step}
    if f[0] == "U":
        p, e0 = int(f[1]), int(f[2]); pts = [int(x) for x in f[3].split(",")] if len(f) > 3 and f[3] else []
        Q = qfam.QGraph(p, e0); n = Q.n; X = Q.X
        # unipotent map fixing the vector X[i0] (i0 = pts[0] or 0): x -> x + det(x, v) v (det 1), order p
        i0 = pts[0] if pts else 0
        v = X[i0]
        Mx = np.array([[1 - v[0] * v[1], v[0] * v[0]], [-v[1] * v[1], 1 + v[0] * v[1]]]) % p     # x -> x + (x0 v1 - x1 v0)(v0, v1)^T... as rows below
        # image of the row vector x: x + det(x, v) v
        det = (X[:, 0] * v[1] - X[:, 1] * v[0]) % p
        Y = (X + det[:, None] * v[None, :]) % p
        perm = vertex_index(Q, Y)
        removed = [i for i in range(n) if (i % (p + 1)) in [q_ % (p + 1) for q_ in pts]]
        return Q.A, perm, removed, {"family": "Q", "p": p, "e0": e0, "theta": Q.theta, "unipotent": [int(v[0]), int(v[1])]}
    if f[0] == "S":
        # "S:p:e0:J:ord[:orbits]" = Q(p, e0) restricted to the split classes J (ind(x0 x1) mod 2 e0; no axis vertices),
        # symmetry: the split torus element diag(tau, 1/tau) with tau of the given (odd) order.  With the optional
        # field `orbits` (comma list or "-" for none) the vertex set is changed by toggling the listed orbits of the
        # symmetry group (orbit numbers as given by split_orbits()).
        import splitclass
        p, e0 = int(f[1]), int(f[2]); J = [int(x) for x in f[3].split(",")]; order = int(f[4])
        Q = qfam.QGraph(p, e0); n = Q.n
        perm = split_perm(Q, order)
        cl = splitclass.split_classes(Q)
        keep = np.isin(cl, J)
        if len(f) > 5 and f[5] not in ("", "-"):
            orb = split_orbits(perm)
            for o in [int(x) for x in f[5].split(",")]:
                keep[orb == o] = ~keep[orb == o]
        assert (keep[perm] == keep).all()
        removed = np.nonzero(~keep)[0].tolist()
        tau = pow(int(Q.g), (p - 1) // order, p)
        return Q.A, perm, removed, {"family": "Q", "p": p, "e0": e0, "theta": Q.theta, "split_order": order,
                                    "matrix": (tau, 0, 0, pow(tau, p - 2, p))}
    if f[0] == "T":
        # "T:p:e0:ord:orbits" = Q(p, e0) restricted to the listed orbits (numbers from split_orbits) of the split
        # torus element diag(tau, 1/tau), tau of the given odd order; symmetry: that element.
        # optional 6th field: "A" = add all axis vertices (x0 x1 = 0), "A0" = those with x1 = 0, "A1" = those with x0 = 0
        p, e0, order = int(f[1]), int(f[2]), int(f[3]); sel = [int(x) for x in f[4].split(",")]
        Q = qfam.QGraph(p, e0); n = Q.n
        perm = split_perm(Q, order); orb = split_orbits(perm)
        size = np.bincount(orb)
        assert all(size[o] == order for o in sel), "only orbits of full length may be listed"
        keep = np.isin(orb, sel)
        if len(f) > 5 and f[5]:
            if f[5] in ("A", "A0"): keep |= (Q.X[:, 1] == 0)
            if f[5] in ("A", "A1"): keep |= (Q.X[:, 0] == 0)
        removed = np.nonzero(~keep)[0].tolist()
        tau = pow(int(Q.g), (p - 1) // order, p)
        return Q.A, perm, removed, {"family": "Q", "p": p, "e0": e0, "theta": Q.theta, "split_order": order,
                                    "matrix": (tau, 0, 0, pow(tau, p - 2, p)), "drop_short": True}
    raise ValueError(spec)


def split_perm(Q, order):
    """the vertex permutation of Q induced by diag(tau, 1/tau), tau of the given order in GF(p)^*"""
    p = Q.p
    assert (p - 1) % order == 0
    tau = pow(Q.g, (p - 1) // order, p); taui = pow(tau, p - 2, p)
    Y = np.stack([(Q.X[:, 0] * tau) % p, (Q.X[:, 1] * taui) % p], axis=1)
    return vertex_index(Q, Y)


def split_orbits(perm):
    """orbit number of every vertex under the cyclic group generated by perm (numbered by smallest element)"""
    n = len(perm); orb = -np.ones(n, dtype=np.int64); k = 0
    for i in range(n):
        if orb[i] >= 0: continue
        j = i
        while orb[j] < 0: orb[j] = k; j = int(perm[j])
        k += 1
    return orb


def vertex_index(Q, Y):
    """index of the class of each row vector of Y among the vertices of Q (classes modulo V0)"""
    p = Q.p; e0 = Q.e0; f = (p - 1) // e0
    V0 = [x for x in range(1, p) if pow(x, f, p) == 1]
    table = -np.ones(p * p, dtype=np.int64)
    for h in V0:
        table[((Q.X[:, 0] * h) % p) * p + (Q.X[:, 1] * h) % p] = np.arange(Q.n)
    idx = table[(Y[:, 0] % p) * p + (Y[:, 1] % p)]
    assert (idx >= 0).all()
    return idx

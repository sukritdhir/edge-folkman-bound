"""Circulants Cay(Z_n, S), S a union of orbits of a multiplier group M <= Z_n^* (with -1) that is NOT of the form
<s, -1> (those were scanned by union_scan.py / union_dfs.py): all subgroups M generated by several elements, with at
most MAXORB orbits on Z_n - 0.  Complete depth-first search over the K4-free unions (exp/union_dfs.search), unweighted
normalised ratio of every maximal union of density >= MIN_DENS (below 1 = the graph arrows (3,3)).
usage: python3 exp/noncyc_scan.py lo hi out.log [maxorb] [budget]         env MIN_DENS, REPORT, ALLGROUPS=1 (also <s,-1>)
"""
import sys, os, time
sys.path.insert(0, "exp"); sys.path.insert(0, ".")
from math import gcd
from union_scan import sym_orbits
import union_dfs

ALL = bool(int(os.environ.get("ALLGROUPS", "0")))
MAXG = int(os.environ.get("MAXGROUPS", "20000"))


def subgroups(n):
    """all subgroups of Z_n^* containing -1 (as frozensets), and the set of those of the form <s, -1>"""
    units = [a for a in range(1, n) if gcd(a, n) == 1]
    def gen(M, s):
        """smallest subgroup containing the subgroup M and s"""
        out = set(M); x = s
        while x not in out:
            out |= {(x * a) % n for a in M}                 # the coset x M
            x = (x * s) % n
        return frozenset(out)
    base = frozenset([1, n - 1])
    cyc = set()
    for s in units:
        cyc.add(gen(base, s))
    allg = set(cyc); frontier = list(cyc)
    while frontier and len(allg) < MAXG:
        new = []
        for M in frontier:
            # one representative per coset of M is enough: use the generators of the cyclic groups
            for C in cyc:
                if C <= M: continue
                # join of M and C: generated by M and the generators of C; C = <s, -1>, take s = any element generating C with -1
                J = set(M)
                for c in C:
                    if c not in J: J = set(gen(frozenset(J), c))
                J = frozenset(J)
                if J not in allg: allg.add(J); new.append(J)
        frontier = new
    return allg, cyc


if __name__ == "__main__":
    lo, hi = int(sys.argv[1]), int(sys.argv[2]); out = open(sys.argv[3], "a")
    maxorb = int(sys.argv[4]) if len(sys.argv) > 4 else 30
    budget = int(sys.argv[5]) if len(sys.argv) > 5 else 100000
    done = set()
    for l in open(sys.argv[3]):
        if l.startswith("# n "): done.add(int(l.split()[2]))
    sys.setrecursionlimit(10000)
    for n in range(lo, hi + 1):
        if n in done: continue
        t0 = time.time()
        allg, cyc = subgroups(n)
        cand = [M for M in allg if (ALL or M not in cyc)]
        ng = 0; bestn = None; trunc = 0
        for M in sorted(cand, key=lambda M: -len(M)):
            if (n - 1) / len(M) > maxorb: break                           # too many orbits (at least (n-1)/|M|)
            orbs = sym_orbits(n, sorted(M))
            if not (2 <= len(orbs) <= maxorb): continue
            ng += 1
            nodes, nmax, b = union_dfs.search(n, orbs, budget, out, "|M| %3d orbits %2d (not cyclic)" % (len(M), len(orbs)))
            if nodes > budget: trunc += 1
            if b is not None and (bestn is None or b[0][0] < bestn[0]): bestn = (b[0][0], b[0][1], len(M), len(orbs))
        line = "# n %d  subgroups %d (of the form <s,-1>: %d)  searched %d  truncated %d  best %s  [%.0fs]" % (
            n, len(allg), len(cyc), ng, trunc, ("ratio %.4f d %d |M| %d orbits %d" % bestn) if bestn else "none", time.time() - t0)
        print(line); out.write(line + "\n"); out.flush(); sys.stdout.flush()
